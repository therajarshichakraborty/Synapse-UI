// Generates src/registry/__index__.tsx (lazy example map) and __names__.ts.
import fs from "node:fs";
import path from "node:path";

const EXAMPLES_DIR = path.join("src", "registry", "examples");
const names = fs.existsSync(EXAMPLES_DIR)
  ? fs
      .readdirSync(EXAMPLES_DIR)
      .filter((f) => f.endsWith(".tsx"))
      .map((f) => f.replace(/\.tsx$/, ""))
      .sort()
  : [];

const entries = names
  .map((n) => `  "${n}": React.lazy(() => import("@/registry/examples/${n}")),`)
  .join("\n");

const index = `// AUTO-GENERATED by scripts/build-docs-index.mjs. Do not edit.
"use client";

import * as React from "react";

export const Index: Record<string, React.LazyExoticComponent<React.ComponentType>> = {
${entries}
};
`;

const namesFile = `// AUTO-GENERATED by scripts/build-docs-index.mjs. Do not edit.
export const exampleNames = ${JSON.stringify(names, null, 2)} as const;
`;

fs.writeFileSync(path.join("src", "registry", "__index__.tsx"), index);
fs.writeFileSync(path.join("src", "registry", "__names__.ts"), namesFile);
console.log(`Generated docs index with ${names.length} examples.`);

// Publish the design tokens for `synapse-ui init`.
const css = fs.readFileSync(path.join("src", "app", "globals.css"), "utf-8");
const start = css.indexOf("/* ───");
fs.writeFileSync(
  path.join("public", "tokens.css"),
  css.slice(start >= 0 ? start : 0).split("/* ── Code (Shiki")[0],
);
